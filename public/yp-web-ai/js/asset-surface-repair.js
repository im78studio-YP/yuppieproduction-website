/* Repair shading data only. Keep geometry positions, UVs, topology order, node paths,
   authored colours and deliberately metallic/black materials intact. */
(function(root){
 'use strict';
 const version='surface-20260918-1';
 function repairGeometry(T,source){
  const p=source.attributes.position,n=source.attributes.normal,index=source.index;
  if(!p||!n)return null; // Missing normals are already generated by GLTFLoader.
  const signs=new Uint8Array(p.count),a=new T.Vector3(),b=new T.Vector3(),c=new T.Vector3(),normal=new T.Vector3();
  const count=index?index.count:p.count;let bad=0;
  function faces(geometry,visit){
   const pos=geometry.attributes.position,idx=geometry.index;
   for(let t=0;t<count;t+=3){const ids=[0,1,2].map(k=>idx?idx.getX(t+k):t+k);
    a.fromBufferAttribute(pos,ids[0]);b.fromBufferAttribute(pos,ids[1]);c.fromBufferAttribute(pos,ids[2]);b.sub(a).cross(c.sub(a));
    if(b.lengthSq()<1e-20)continue;b.normalize();visit(ids,b);
   }
  }
  faces(source,(ids,face)=>ids.forEach(id=>{normal.fromBufferAttribute(n,id);const dot=normal.normalize().dot(face);if(dot<-.1){signs[id]|=1;bad++;}else if(dot>.1)signs[id]|=2;}));
  if(!bad)return null;
  // Split only when a shared vertex needs different signs on different faces.
  const split=!!index&&signs.some(sign=>sign===3),geometry=split?source.toNonIndexed():source.clone();
  const repaired=geometry.attributes.normal,tangent=geometry.attributes.tangent;
  const flip=id=>{repaired.setXYZ(id,-repaired.getX(id),-repaired.getY(id),-repaired.getZ(id));if(tangent)tangent.setW(id,-tangent.getW(id));};
  if(split)faces(geometry,(ids,face)=>ids.forEach(id=>{normal.fromBufferAttribute(repaired,id);if(normal.normalize().dot(face)<-.1)flip(id);}));
  else signs.forEach((sign,id)=>{if(sign&1)flip(id);});
  repaired.needsUpdate=true;if(tangent)tangent.needsUpdate=true;
  return{geometry,corners:bad,split};
 }
 function inheritedDefault(gltf,mesh,allowExported){
  const assoc=gltf.parser?.associations.get(mesh),primitive=gltf.parser?.json.meshes?.[assoc?.meshes]?.primitives?.[assoc?.primitives];
  if(!primitive)return false;if(primitive.material===undefined)return true;
  if(!allowExported)return false;
  const def=gltf.parser.json.materials?.[primitive.material],pbr=def?.pbrMetallicRoughness;
  return !!pbr&&Object.keys(def).every(k=>k==='pbrMetallicRoughness')&&Object.keys(pbr).every(k=>['metallicFactor','roughnessFactor'].includes(k))&&pbr.metallicFactor===1&&pbr.roughnessFactor===1;
 }
 function apply(T,gltf,item={}){
  const scene=gltf.scene;if(!scene||scene.userData.ypSurfaceRepairVersion===version)return{normalMeshes:0,defaultMaterials:0};
  const report={normalMeshes:0,defaultMaterials:0,corners:0},geometries=new Map(),materials=new Map();
  const allowExported=/^(standee-|counter-set-)/.test(item.catalogId||'');
  scene.traverse(mesh=>{
   if(!mesh.isMesh)return;
   if(!geometries.has(mesh.geometry))geometries.set(mesh.geometry,repairGeometry(T,mesh.geometry));
   const repaired=geometries.get(mesh.geometry);if(repaired){mesh.geometry=repaired.geometry;report.normalMeshes++;report.corners+=repaired.corners;}
   // TVs have a dedicated black chassis/screen material pipeline. Do not whiten them.
   if(!item.tvDisplay&&inheritedDefault(gltf,mesh,allowExported)){
    const convert=m=>{if(!m?.isMeshStandardMaterial)return m;
     if(!materials.has(m)){const next=m.clone();next.metalness=0;next.roughness=.72;next.userData.ypFallbackSurface=true;materials.set(m,next);}
     report.defaultMaterials++;return materials.get(m);
    };mesh.material=Array.isArray(mesh.material)?mesh.material.map(convert):convert(mesh.material);
   }
  });
  // The GLTF has its own loaded resources; repaired geometries no longer reference these originals.
  for(const [original,repaired] of geometries)if(repaired)original.dispose();
  scene.userData.ypSurfaceRepairVersion=version;scene.userData.ypSurfaceRepair=report;return report;
 }
 const repairedPreview=item=>/^(imported-|standee-|counter-set-)/.test(item.catalogId||'')||item.catalogId==='high-table-stool-set';
 root.YPAssetSurfaceRepair={version,repairGeometry,apply,repairedPreview};
})(globalThis);
