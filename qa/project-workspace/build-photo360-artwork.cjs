// Package the exact approved BD_01 PNG without resizing or recreating the art.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const source=path.resolve(__dirname,'../../../AW/BD_01.png');
const target=path.resolve(__dirname,'../../public/yp-web-ai/assets/branding/photo360-artwork.js');
const bytes=fs.readFileSync(source),hash=b=>crypto.createHash('md5').update(b).digest('hex');
const payload={name:'BD_01.png',data:'data:image/png;base64,'+bytes.toString('base64'),aspect:bytes.readUInt32BE(16)/bytes.readUInt32BE(20),sourceMD5:hash(bytes)};
const content='/* Approved original BD_01.png; generated by build-photo360-artwork.cjs. */\nglobalThis.YPPhoto360Artwork=Object.freeze('+JSON.stringify(payload)+');\n';
fs.writeFileSync(target+'.tmp',content);if(hash(fs.readFileSync(target+'.tmp'))!==hash(Buffer.from(content)))throw Error('Checksum mismatch');fs.renameSync(target+'.tmp',target);
console.log('Packaged BD_01.png unchanged',payload.sourceMD5);
